import Tag, { Signal } from "./Tag.jsx";
import { buildQuestions } from "../analysis/summary.js";

export default function Gaps({ r }) {
  const qs = buildQuestions(r);
  return (
    <>
      <section>
        <h2>Unanswered questions</h2>
        <p className="sub">Questions your sources leave open. These are generated by the tool, not found in the sources.</p>
        {qs.length ? (
          <ul className="plain">
            {qs.map((x, i) => (
              <li key={i}><Signal /> <b>{x.t}</b> <span style={{ color: "var(--mu)" }}>{x.w}</span></li>
            ))}
          </ul>
        ) : (
          <p className="empty">No open questions detected.</p>
        )}
      </section>

      <section>
        <h2>Information gaps</h2>
        <p className="sub">Missing from every source, or backed by only one.</p>
        {r.gaps.length ? (
          r.gaps.map((x, i) => (
            <div className="card item" key={i}>
              <h3>{x.a.label} <Tag k="s">missing everywhere</Tag></h3>
              <p className="sub" style={{ margin: "4px 0 0" }}>{x.a.hint}</p>
            </div>
          ))
        ) : (
          <p className="empty">Every key point is mentioned by at least one source.</p>
        )}
        {r.single.map((x, i) => {
          const j = x.h.findIndex((m) => m.length);
          return (
            <div className="card item" key={"s" + i}>
              <h3>{x.a.label} <Tag k="s">single source</Tag></h3>
              <p className="sub" style={{ margin: "4px 0 0" }}>Only {r.S[j].l} mentions this.</p>
            </div>
          );
        })}
      </section>
    </>
  );
}
